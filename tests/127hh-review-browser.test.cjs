"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {JSDOM}=require("jsdom");
const source=fs.readFileSync(path.join(__dirname,"..","127hh-review.html"),"utf8");
const dom=new JSDOM(source,{runScripts:"dangerously",url:"https://review.local/127hh-review.html"});
const {document}=dom.window;
assert.equal(document.title,"ESTA · Nghiệm thu giao diện 127 Hồng Hà");
assert.equal(document.querySelectorAll("nav button[data-page]").length,5);
assert.equal(document.querySelectorAll("#months button").length,13);
assert.ok(document.querySelector('nav button[data-page="overview"]').getAttribute("aria-current"));
const work=document.querySelector('nav button[data-page="work"]');work.click();
assert.equal(document.querySelector('[data-view="work"]').hidden,false);
assert.equal(document.querySelector('[data-view="overview"]').hidden,true);
assert.equal(document.querySelector("#pageTitle").textContent,"Công việc · 127 Hồng Hà");
const workSearch=document.getElementById("workSearch");
workSearch.value="PCCC";workSearch.dispatchEvent(new dom.window.Event("input",{bubbles:true}));
assert.equal([...document.querySelectorAll("#workRows tr")].filter(r=>!r.hidden).length,1);
document.querySelector('nav button[data-page="materials"]').click();
const month=document.querySelectorAll("#months button")[2];month.click();
assert.equal(month.getAttribute("aria-pressed"),"true");
assert.equal([...document.querySelectorAll("#months button")].filter(b=>b.getAttribute("aria-pressed")==="true").length,1);
// Mobile review must use semantic, width-contained cards and a single month picker.
assert.match(source,/@media\(max-width:700px\)/);
assert.match(source,/\.tablewrap tbody tr\{display:grid/);
assert.match(source,/\.tablewrap tbody tr\[hidden\]\{display:none!important\}/);
assert.match(source,/\.months\{display:none\}/);
assert.match(source,/\.calendar\{display:none\}/);
assert.match(source,/nav\{display:grid;grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
const materialTable=document.querySelector('[data-view="materials"] table');
assert.ok([...materialTable.querySelectorAll("tbody tr")].every(tr=>[...tr.cells].every(td=>td.dataset.label)), "every mobile material card field must be labeled");
assert.equal(document.querySelectorAll("#mobileMonth option").length,13);
const mobileMonth=document.querySelector("#mobileMonth");
assert.equal(mobileMonth.value,"2","desktop month change should sync to phone");
mobileMonth.value="9";mobileMonth.dispatchEvent(new dom.window.Event("change",{bubbles:true}));
assert.equal(document.querySelectorAll("#months button")[9].getAttribute("aria-pressed"),"true","phone choice must sync to desktop");
assert.equal([...document.querySelectorAll("#months button")].filter(b=>b.getAttribute("aria-pressed")==="true").length,1);
const sampleDays=[...document.querySelectorAll("#mobileMaintenance .maintenanceItem")];
assert.equal(sampleDays.length,3,"phone maintenance must show the same events as desktop");
assert.equal(document.querySelectorAll("#calendar .event").length,sampleDays.length,"both views share one event model");
assert.ok(sampleDays.every(card=>card.querySelector("time")?.getAttribute("datetime")));
document.querySelector("#exportButton").click();
assert.match(document.getElementById("notification").textContent,/không ghi dữ liệu/);
assert.ok(!source.includes("supabase.co"),"review fixture cannot connect to production");
console.log("PASS 127HH desktop/mobile review: cards, responsive nav, month sync, agenda, search, safe actions");
dom.window.close();
