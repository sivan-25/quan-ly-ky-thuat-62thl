"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {JSDOM}=require("jsdom");
const root=path.resolve(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const html=read("127hh-trial.html"),css=read("127hh-trial.css"),js=read("127hh-trial.js");
assert.match(html,/DÙNG THỬ|Dùng thử|TRẢI NGHIỆM CÓ THAO TÁC/);
assert.match(css,/@media\(max-width:720px\)/);
assert.match(css,/overflow-x:clip/);
assert.match(css,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.ok(!js.includes("supabase.co"));
assert.ok(!/\bfetch\s*\(|\bXMLHttpRequest\b/.test(js),"trial app must never call any live backend");
assert.ok(!html.includes('src="app.js"'),"isolation from production runtime");
const dom=new JSDOM(html,{runScripts:"outside-only",url:"https://127hh-trial.test/"});
const {window}=dom,doc=window.document;
window.scrollTo=()=>{};
window.confirm=()=>true;
window.eval(js);
const $=id=>doc.getElementById(id);
const click=(s)=>{const el=doc.querySelector(s);assert.ok(el,"missing "+s);el.click();return el;};
const submit=()=>{$("editForm").dispatchEvent(new window.Event("submit",{bubbles:true,cancelable:true}));};
const change=(el)=>el.dispatchEvent(new window.Event("change",{bubbles:true}));
const input=(el)=>el.dispatchEvent(new window.Event("input",{bubbles:true}));
const data=()=>window.ESTA127Trial.data();
assert.equal(data().work.length,3);
assert.equal(doc.querySelectorAll("#nav button[data-page]").length,5);
click('[data-page="work"]');
click('[data-add="work"]');
assert.equal($("editor").hasAttribute("open"),true);
$("field-title").value="Kiểm tra thử nghiệm trên điện thoại";
$("field-assignee").value="Người thử nghiệm";
$("field-star").value="true";
submit();
assert.equal(data().work.length,4);
assert.ok(data().work.some(w=>w.title.includes("điện thoại")&&w.star));
assert.equal($("editor").hasAttribute("open"),false);
$("workSearch").value="điện thoại";input($("workSearch"));
assert.equal($("workList").querySelectorAll(".record").length,1,"filter by search must work");
click('[data-action="finish"][data-kind="work"]');
assert.equal(data().work.filter(w=>w.title.includes("điện thoại"))[0].status,"done");
click('[data-page="materials"]');
assert.equal($("materialMetrics").querySelectorAll(".metric").length,4);
$("materialMonth").value="11";change($("materialMonth"));
click('[data-action="stockIn"][data-kind="material"][data-id="m1"]');
assert.equal($("dialogTitle").textContent,"Nhập vật tư");
$("field-qty").value="5";
$("field-date").value="2026-11-06";
submit();
assert.equal(data().txns.length,6);
const stockIn=Number(data().txns.at(-1).qty);assert.equal(stockIn,5);
assert.match($("materialList").textContent,/31/,"November closing balance updated");
click('[data-action="stockOut"][data-kind="material"][data-id="m1"]');
$("field-qty").value="999";
submit();
assert.equal(data().txns.length,6,"outbound quantity must be checked against stock");
assert.match($("feedback").textContent,/Không đủ tồn kho/);
click("#cancelEditor");
click('[data-page="tools"]');
click('[data-add="tool"]');
$("field-name").value="Kìm thử nghiệm";
$("field-qty").value="1";
submit();
assert.ok(data().tools.some(x=>x.name==="Kìm thử nghiệm"));
click('[data-page="maintenance"]');
click('[data-action="duplicate"][data-kind="maintenance"][data-id="a1"]');
assert.equal(data().maintenance.length,4);
assert.ok(data().maintenance.some(x=>x.id!=="a1"&&x.title==="Kiểm tra chiếu sáng"&&x.date==="2026-11-07"));
click("#nextMonth");
assert.equal($("maintenanceMonth").value,"2026-12");
assert.ok(window.localStorage.getItem("esta.127hh.interactive-trial.v1"),"data persists locally");
click("#resetTrial");
assert.equal(data().work.length,3);
assert.equal(data().txns.length,5);
assert.equal(data().tools.length,3);
assert.equal(data().maintenance.length,3);
console.log("PASS 127HH interactive trial: five screens, CRUD, local persistence, stock validation, months, calendar and reset");
window.close();
