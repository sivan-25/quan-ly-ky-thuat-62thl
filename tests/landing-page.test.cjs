'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root=path.resolve(__dirname,'..');
const markup=fs.readFileSync(path.join(root,'landing/index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'landing/landing.css'),'utf8');
assert.match(markup,/<html lang="vi">/);
assert.match(markup,/<meta name="viewport" /);
assert.match(markup,/<title>ESTA/);
assert.match(markup,/<main id="main">/);
assert.match(markup,/id="tinh-nang"/);
assert.match(markup,/id="cach-hoat-dong"/);
assert.match(markup,/id="giao-dien"/);
assert.match(markup,/(GIAO DIỆN MINH HỌA|KHÔNG PHẢI DỮ LIỆU THỰ)/);
assert.match(markup,/<a class="btn btn-primary" href="\/">/);
assert.ok((markup.match(/href="\/"/g)||[]).length>=3,'all CTAs open existing app without redirect changes');
assert.ok(!/(<form|https?:\/\/.*login|type="password")/i.test(markup),'landing must not duplicate user login fields');
assert.ok(!/script\s+src=.*app\.js/i.test(markup),'landing must not load authenticated application JS');
assert.ok(css.includes('--blue-light:#edf5ff')&&css.includes('background:#fff'),'approved light palette');
assert.ok(css.includes('prefers-reduced-motion'),'reduced motion supported');
const local=markup.match(/href="\.\/landing\.css\?[^"]+"/);
assert.ok(local,'linked CSS with cache version is required');
console.log('PASS: independent ESTA landing page, anchors, CTA, light palette and no app/auth side effects');
